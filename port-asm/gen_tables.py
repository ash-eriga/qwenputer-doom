#!/usr/bin/env python3
"""Generate the fixed-point tables for ray0.S."""
import argparse
import math
from pathlib import Path

W, H = 96, 60
NTAB = 256

ap = argparse.ArgumentParser()
ap.add_argument('--step-tiles', type=float, default=1.0, help='ray step length in tiles')
ap.add_argument('--suffix', default='full', help='output suffix')
args = ap.parse_args()

def s8(v):
    return str(v)

print_tables = []
print_tables.append('# generated by gen_tables.py; do not edit')
print_tables.append('    .section .rodata')
print_tables.append('    .align 1')
print_tables.append('    .globl sin_tab')
print_tables.append('sin_tab:')
vals = [round(math.sin(2 * math.pi * i / NTAB) * 256) for i in range(NTAB)]
for i in range(0, NTAB, 16):
    print_tables.append('    .half ' + ','.join(map(str, vals[i:i+16])))
print_tables.append('    .globl cos_tab')
print_tables.append('cos_tab:')
vals = [round(math.cos(2 * math.pi * i / NTAB) * 256) for i in range(NTAB)]
for i in range(0, NTAB, 16):
    print_tables.append('    .half ' + ','.join(map(str, vals[i:i+16])))

# Camera angle offsets in 1/256-turn units, roughly a 60 degree field of view.
print_tables.append('    .globl camoff_tab')
print_tables.append('camoff_tab:')
fov_units = 256 * 60 / 360
cam = [round((x / (W - 1) - 0.5) * fov_units) for x in range(W)]
for i in range(0, W, 16):
    print_tables.append('    .byte ' + ','.join(map(str, cam[i:i+16])))

# Wall height by fixed-step count; 45 pixels at one tile.
print_tables.append('    .globl height_tab')
print_tables.append('height_tab:')
h = [0] * 65
for steps in range(1, 65):
    h[steps] = min(H, max(1, round(45 / (steps * args.step_tiles))))
for i in range(0, 65, 16):
    chunk = h[i:i+16]
    if chunk:
        print_tables.append('    .byte ' + ','.join(map(str, chunk)))

rows = [
    '1111111111111111',
    '1000000000000001',
    '1000000000000001',
    '1000002000000001',
    '1000002000000001',
    '1000000000000001',
    '1000000000000001',
    '1111000000001111',
    '1000000000000001',
    '1000000000000001',
    '1000000000000001',
    '1000000000000001',
    '1000000000000001',
    '1000000000000001',
    '1000000000000001',
    '1111111111111111',
]
print_tables.append('    .globl map')
print_tables.append('map:')
for row in rows:
    print_tables.append('    .byte ' + ','.join(row))

# X/Y are packed as x | y << 16 in the hot ray loop. After pos >> 8 and a 0x0f0f mask,
# the index is xtile + ytile * 256, so this expanded map makes cell lookup three instructions.
print_tables.append('    .globl map256')
print_tables.append('map256:')
for row in rows:
    for x in row:
        print_tables.append('    .byte ' + x)
    print_tables.append('    .zero 240')

# Column kernels: one fixed straight-line 16-SW sequence per ray step count. STRIDE is 80
# bytes; each real case is 16 stores + one jump back (68 bytes) plus 12 bytes of padding.
KSTRIDE = 80
kernel = []
kernel.append('# generated column kernels')
kernel.append('    .section .text')
kernel.append('    .align 4')
kernel.append('    .globl colkern_base')
kernel.append('colkern_base:')
kernel.append('    .space 80')  # case 0 is never valid; keep the stride exact
for steps in range(1, 65):
    hh = h[steps]
    top = (H - hh) // 2
    floorpix = H - top - hh
    ceiln = (top + 3) // 4
    floorn = (floorpix + 3) // 4
    walln = 16 - ceiln - floorn
    colors = (['a2'] * ceiln) + (['a3'] * walln) + (['a4'] * floorn)
    assert len(colors) == 16, (steps, hh, ceiln, walln, floorn)
    while len(kernel) and False:
        pass
    kernel.append(f'colkern_{steps}:')
    for i, reg in enumerate(colors):
        kernel.append(f'    sw {reg},{4 * i}(s4)')
    kernel.append('    j colkern_done')
    kernel.append(f'    .space {KSTRIDE - 17 * 4}')

kout = Path(__file__).with_name(f'kernels-{args.suffix}.S')
kout.write_text('\n'.join(kernel) + '\n')

out = Path(__file__).with_name(f'tables-{args.suffix}.S')
out.write_text('\n'.join(print_tables) + '\n')
print(out)
print(kout)
